/**
 * The backend's logo, named for screen readers by the product's name. The
 * generic REST tile has no owner to borrow a logo from, so it gets an icon.
 */
export function BackendLogo({
  backend,
  className,
}: {
  backend: Backend
  className?: string
}) {
  const mark = MARKS[backend.id]

  if (!mark) {
    return (
      <Braces
        role="img"
        aria-label={backend.name}
        className={cn("h-8 w-auto", className)}
      />
    )
  }

  return (
    <svg
      role="img"
      aria-label={backend.name}
      viewBox={mark.viewBox}
      fill="currentColor"
      className={cn("h-8 w-auto", className)}
    >
      <title>{backend.name}</title>
      {mark.paths.map((d) => (
        <path key={d} d={d} />
      ))}
    </svg>
  )
}
